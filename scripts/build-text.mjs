import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sdk = process.env.ANDROID_HOME ?? process.env.ANDROID_SDK_ROOT ??
  (process.env.LOCALAPPDATA ? path.join(process.env.LOCALAPPDATA, "Android", "Sdk") : undefined);
if (!sdk) throw new Error("Set ANDROID_HOME to an Android SDK with platform 35 and build-tools 35.0.0.");
const androidJar = path.join(sdk, "platforms", "android-35", "android.jar");
const d8Jar = path.join(sdk, "build-tools", "35.0.0", "lib", "d8.jar");
for (const required of [androidJar, d8Jar]) {
  if (!(await stat(required)).isFile()) throw new Error(`Missing helper build prerequisite: ${required}`);
}
const output = path.join(root, "android", "build", "text");
const classes = path.join(output, "classes");
const dex = path.join(output, "dex");
await rm(classes, { recursive: true, force: true });
await rm(dex, { recursive: true, force: true });
await mkdir(classes, { recursive: true });
await mkdir(dex, { recursive: true });
const options = { cwd: root, stdio: "inherit", windowsHide: true };
execFileSync("javac", [
  "--release", "8", "-Xlint:-options", "-classpath", androidJar,
  "-d", classes, path.join(root, "android", "TextMain.java"),
], options);
const packagePath = path.join(classes, "dev", "mobileuse", "text");
const inputs = (await readdir(packagePath)).filter((file) => file.endsWith(".class")).sort();
execFileSync("java", [
  "-cp", d8Jar, "com.android.tools.r8.D8", "--release", "--lib", androidJar, "--min-api", "30",
  "--output", dex, ...inputs.map((file) => path.join(packagePath, file)),
], options);
const bytes = await readFile(path.join(dex, "classes.dex"));
const sha256 = createHash("sha256").update(bytes).digest("hex");
await writeFile(path.join(root, "src", "text-helper-data.ts"),
  "// Generated by scripts\\build-text.mjs from android\\TextMain.java; do not edit.\n" +
  `export const textHelperSha256 = "${sha256}";\n` +
  `export const textHelperBase64 = "${bytes.toString("base64")}";\n`);
console.log(`Built text helper: ${sha256}`);
